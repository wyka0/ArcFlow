#!/usr/bin/env node
/**
 * ArcFlow Phase 15 — Deployment-Script Compile Gate
 *
 * Foundry's standard `forge build` / `forge test` do NOT compile
 * `script_disabled/DeployArcFlowV2.s.sol`, because the scan directories are
 * `src = "contracts"`, `test = "test"`, `script = "script"`. A mirrored
 * harness test (test/ChainGuard.t.sol) proves the guard LOGIC, but only
 * compiling the actual script proves the script file itself is valid.
 *
 * This gate compiles the REAL deployment script non-transactionally:
 *   - Generates a temporary Foundry config OUTSIDE the repository and runs
 *     `forge build` with FOUNDRY_CONFIG pointing at it (no repo file reads or
 *     writes beyond normal source reads).
 *   - The temp config sets `script = "script_disabled"` so the real deployment
 *     script is included, and points `out` / `cache_path` at a fresh temp
 *     directory, so no stale or repo artifact can be trusted and the repo
 *     working tree stays untouched.
 *   - Remappings are pinned as a TOML array. (FOUNDRY_REMAPPINGS is NOT used:
 *     on this Windows platform the env var does not split mappings on spaces,
 *     verified 2026-10-11 — the whole value collapsed into one mapping.)
 *   - Verifies exit code 0, that the fresh artifact exists, and that the
 *     artifact metadata matches the required settings (solc 0.8.24,
 *     optimizer 200 runs, via_ir = true).
 *
 * This NEVER executes the deployment script: no RPC, no simulation, no
 * broadcast. It is a pure offline compilation.
 *
 * Usage:
 *   node scripts/compile-deploy-script.mjs   (or: npm run compile:deploy-script)
 *
 * Exit codes:
 *   0 = actual deployment script compiled clean under required settings
 *   1 = compilation failed, artifact missing, or settings mismatch (BLOCKER)
 */

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// Forge resolution (Phase 20.1): prefer an explicit override, then a vendored
// foundry_bin/ directory (original layout), then `forge` on the PATH (the
// documented Foundry installation method). No vendored binary is required.
const FORGE = process.env.FOUNDRY_BIN && fs.existsSync(process.env.FOUNDRY_BIN)
  ? process.env.FOUNDRY_BIN
  : fs.existsSync(path.join(ROOT, "foundry_bin", process.platform === "win32" ? "forge.exe" : "forge"))
    ? path.join(ROOT, "foundry_bin", process.platform === "win32" ? "forge.exe" : "forge")
    : process.platform === "win32" ? "forge.exe" : "forge";
const SCRIPT_REL = path.join("script_disabled", "DeployArcFlowV2.s.sol");
const ARTIFACT_REL = path.join("out", "DeployArcFlowV2.s.sol", "DeployArcFlowV2.json");

// Files excluded from the compile gate. Both are one-off typehash/selector
// investigation scripts from earlier phases that contain pre-existing
// duplicate-declaration errors (49 x Error 2333, verified 2026-10-11) and are
// superseded by test/SelectorRegression.t.sol. They are NOT part of the
// deployment path and are unrelated to DeployArcFlowV2.s.sol, which MUST
// compile. Every other source in contracts/, test/, and script_disabled/ is
// compiled by this gate.
const SKIP_FILES = [
  "*/ComputeTypehashes3.s.sol",
  "*/FindTypehashFinal.s.sol",
];

const REQUIRED = {
  solc: "0.8.24",
  optimizerRuns: 200,
  viaIR: true,
};

// Pinned remappings (relative to repo root, proven 2026-10-11 with an
// external FOUNDRY_CONFIG). Covers every import prefix used by the sources:
// `forge-std/...`, `openzeppelin-contracts/...`, `@openzeppelin/contracts/...`;
// `lib/...` and `./`/`../` imports resolve via the base path.
const REMAPPINGS = [
  "forge-std/=lib/forge-std/src/",
  "openzeppelin-contracts/=lib/openzeppelin-contracts/",
  "@openzeppelin/contracts/=node_modules/@openzeppelin/contracts/",
];

function writeTempConfig(tmp) {
  const toml = [
    "# AUTO-GENERATED by scripts/compile-deploy-script.mjs — safe to delete.",
    "# Compiles the repo sources PLUS script_disabled/ with out/cache outside the repo.",
    "[profile.default]",
    'src = "contracts"',
    'test = "test"',
    'script = "script_disabled"',
    `out = ${JSON.stringify(path.join(tmp, "out").replace(/\\/g, "/"))}`,
    `cache_path = ${JSON.stringify(path.join(tmp, "cache").replace(/\\/g, "/"))}`,
    'libs = ["lib"]',
    `solc_version = "${REQUIRED.solc}"`,
    "optimizer = true",
    `optimizer_runs = ${REQUIRED.optimizerRuns}`,
    "via_ir = true",
    "remappings = [",
    ...REMAPPINGS.map((r) => `  ${JSON.stringify(r)},`),
    "]",
    "",
  ].join("\n");
  const p = path.join(tmp, "foundry-deploy-compile.toml");
  fs.writeFileSync(p, toml, "utf8");
  return p;
}

function main() {
  if (process.env.FOUNDRY_BIN && !fs.existsSync(process.env.FOUNDRY_BIN)) {
    console.error(`❌ FAIL: FOUNDRY_BIN is set but the file does not exist (value withheld).`);
    process.exit(1);
  }
  if (!fs.existsSync(path.join(ROOT, SCRIPT_REL))) {
    console.error(`❌ FAIL: deployment script not found at ${SCRIPT_REL}`);
    process.exit(1);
  }

  // Fresh isolated workspace OUTSIDE the repository.
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "arcflow-deploy-compile-"));
  const configFile = writeTempConfig(tmp);

  console.log("Compiling the actual deployment script (non-transactional)...");
  console.log("  command : forge build " + SKIP_FILES.map((s) => `--skip ${s}`).join(" "));
  console.log(`  file    : ${SCRIPT_REL}`);
  console.log(`  config  : ${configFile} (outside repo, freshly generated)`);
  console.log(`  out     : ${path.join(tmp, "out")} (outside repo, fresh)`);
  console.log(`  cache   : ${path.join(tmp, "cache")} (outside repo, fresh)`);
  console.log(`  skipped : ${SKIP_FILES.join(", ")} (broken one-off investigation scripts, not deployment path)`);

  const result = spawnSync(FORGE, ["build", ...SKIP_FILES.flatMap((s) => ["--skip", s])], {
    cwd: ROOT,
    env: { ...process.env, FOUNDRY_CONFIG: configFile },
    encoding: "utf8",
  });

  const output = `${result.stdout ?? ""}${result.stderr ?? ""}`;
  const interesting = output
    .split("\n")
    .filter((l) => /error|Compiler run|Compiling|warning/i.test(l))
    .slice(0, 20);
  for (const line of interesting) console.log(`  | ${line.trim()}`);

  let ok = true;

  if (result.status !== 0) {
    ok = false;
    console.error(`❌ FAIL: forge build exited with code ${result.status}`);
  }

  const artifactPath = path.join(tmp, ARTIFACT_REL);
  if (ok && !fs.existsSync(artifactPath)) {
    ok = false;
    console.error(`❌ FAIL: expected fresh artifact not found: ${artifactPath}`);
  }

  if (ok) {
    try {
      const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
      const settings = artifact.metadata?.settings ?? {};
      const compiler = artifact.metadata?.compiler?.version ?? "unknown";
      const runs = settings.optimizer?.runs;
      const viaIR = settings.viaIR === true;
      const optimizerEnabled = settings.optimizer?.enabled === true;
      if (!compiler.startsWith(`${REQUIRED.solc}+`)) {
        ok = false;
        console.error(`❌ FAIL: compiler version ${compiler} does not match ${REQUIRED.solc}`);
      }
      if (!optimizerEnabled || runs !== REQUIRED.optimizerRuns) {
        ok = false;
        console.error(`❌ FAIL: optimizer settings mismatch (enabled=${optimizerEnabled}, runs=${runs})`);
      }
      if (!viaIR) {
        ok = false;
        console.error(`❌ FAIL: viaIR is not enabled in artifact metadata`);
      }
      if (ok) {
        const bytecodeLen = (artifact.bytecode?.object ?? "").length;
        console.log(`  artifact: ${path.basename(artifactPath)} (${bytecodeLen} hex chars creation code)`);
        console.log(`  settings: solc ${compiler}, optimizer ${runs} runs, viaIR ${viaIR}`);
      }
    } catch (e) {
      ok = false;
      console.error(`❌ FAIL: could not parse artifact metadata: ${e.message}`);
    }
  }

  // Cleanup isolated build output regardless of outcome.
  try {
    fs.rmSync(tmp, { recursive: true, force: true });
  } catch {
    /* temp dir cleanup is best-effort */
  }

  if (!ok) {
    console.error("");
    console.error("RESULT: ❌ COMPILE GATE FAILED — deployment approval must not proceed.");
    console.error("        The REAL deployment script did not compile under required settings.");
    process.exit(1);
  }

  console.log("");
  console.log("RESULT: ✅ COMPILE GATE PASSED — the actual deployment script");
  console.log(`        (${SCRIPT_REL}) compiles clean with solc ${REQUIRED.solc},`);
  console.log(`        optimizer ${REQUIRED.optimizerRuns} runs, via_ir = true.`);
  process.exit(0);
}

main();
